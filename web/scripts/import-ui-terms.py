"""Import display-only name pairs; never copy ROM payloads or descriptions.

Usage: python3 scripts/import-ui-terms.py /path/to/terms.json [/path/to/baseline.csv]
"""
import csv
import hashlib
import json
from collections import defaultdict
from pathlib import Path
import sys

source = Path(sys.argv[1])
raw = source.read_bytes()
document = json.loads(raw)
categories = ('job', 'ability', 'item', 'skill_school', 'region', 'location')
pairs_by_category = {category: defaultdict(set) for category in categories}

def add(category, english, chinese):
    # Only complete, plain names with an actual Chinese translation.
    if (english and chinese and english != chinese and '\\' not in english + chinese
            and '<unknown:' not in english + chinese
            and any('\u3400' <= char <= '\u9fff' for char in chinese)):
        pairs_by_category.setdefault(category, defaultdict(set))[english].add(chinese)

for record in document['records']:
    if record['category'] in categories:
        add(record['category'], record['english'], record['canonical_zh'])

catalog_note = ''
if len(sys.argv) > 2:
    catalog = Path(sys.argv[2])
    # Named tables only; never import dialogue, descriptions or raw payloads.
    tables = {0: 'character', 6: 'quest', 14: 'law', 24: 'bazaar'}
    with catalog.open(encoding='utf-8-sig', newline='') as stream:
        for record in csv.DictReader(stream):
            parts = record['id'].split(':')
            if len(parts) != 4 or parts[:2] != ['message', '0']:
                continue
            table, index = int(parts[2]), int(parts[3])
            if table not in tables or (table == 24 and index >= 107):
                continue
            add(tables[table], json.loads(record['context']).get('english', ''), record['text'])
    catalog_note = f'// Name catalog SHA-256: {hashlib.sha256(catalog.read_bytes()).hexdigest()}\n'

result = {}
ambiguous = 0
for category, pairs in pairs_by_category.items():
    result[category] = {en: next(iter(zh)) for en, zh in sorted(pairs.items()) if len(zh) == 1}
    ambiguous += sum(len(zh) > 1 for zh in pairs.values())
output = Path(__file__).resolve().parents[1] / 'src/ui/gameTerms.ts'
output.write_text(
    '// Generated by scripts/import-ui-terms.py; UI display only.\n'
    + catalog_note
    + f'// Source revision: {document["current_revision"]}\n'
    f'// Source SHA-256: {hashlib.sha256(raw).hexdigest()}\n'
    f'// Conflicting English names omitted: {ambiguous}\n'
    'export const gameTerms: Record<string, Record<string, string>> = '
    + json.dumps(result, ensure_ascii=False, indent=2) + ';\n'
)
print({category: len(pairs) for category, pairs in result.items()}, 'ambiguous:', ambiguous)
